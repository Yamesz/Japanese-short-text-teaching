const ZELDA40_FURIGANA_ENTRIES = Object.entries(ZELDA40_FURIGANA)
  .sort((left, right) => right[0].length - left[0].length);

function zelda40RenderFurigana(value) {
  const text = String(value);
  let html = '';
  let index = 0;

  while (index < text.length) {
    const entry = ZELDA40_FURIGANA_ENTRIES.find(([surface]) => text.startsWith(surface, index));
    if (entry) {
      html += `<ruby>${zelda40Escape(entry[0])}<rt>${zelda40Escape(entry[1])}</rt></ruby>`;
      index += entry[0].length;
    } else {
      html += zelda40Escape(text[index]);
      index += 1;
    }
  }

  return html;
}

