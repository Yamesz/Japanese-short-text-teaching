function toggleZelda40Conjugation(id, button) {
  const table = document.getElementById(id);
  if (!table) return;
  const isOpen = table.classList.toggle('active');
  button.setAttribute('aria-expanded', String(isOpen));
  button.textContent = isOpen ? '📊 收起動詞活用變化表' : '📊 展開動詞活用變化表';
}

function renderZelda40Conjugation(conjugation, id) {
  if (!conjugation) return '';
  return `
    <div class="zelda-vocab-type">🏃 ${zelda40Escape(conjugation.className)}</div>
    <button class="conjugation-toggle" type="button" aria-expanded="false" aria-controls="${id}" onclick="toggleZelda40Conjugation('${id}', this)">📊 展開動詞活用變化表</button>
    <div id="${id}" class="conjugation-table-wrapper zelda-conjugation-wrapper">
      <table class="conjugation-table">
        <thead><tr><th>辭書形</th><th>ます形</th><th>過去式</th><th>て形</th><th>ない形</th></tr></thead>
        <tbody><tr>
          <td>${zelda40Escape(conjugation.dictionary)}</td>
          <td>${zelda40Escape(conjugation.masu)}</td>
          <td>${zelda40Escape(conjugation.past)}</td>
          <td>${zelda40Escape(conjugation.te)}</td>
          <td>${zelda40Escape(conjugation.nai)}</td>
        </tr></tbody>
      </table>
    </div>
  `;
}

function renderZelda40ExampleList(examples) {
  const validExamples = examples
    .filter(example => example && example.jp && example.cn)
    .slice(0, 3);
  if (!validExamples.length) return '';

  return `
    <div class="zelda-examples">
      ${validExamples.map((example, index) => `
        <div class="example-box">
          <div class="example-jp">例句${index + 1}：${zelda40Escape(example.jp)} <button class="audio-btn" type="button" data-speak="${zelda40Escape(example.jp)}">🔊</button></div>
          <div class="example-cn">（${zelda40Escape(example.cn)}）</div>
        </div>
      `).join('')}
    </div>
  `;
}

function renderZelda40Examples(item, extraExamples = []) {
  const examples = [
    ...(item.example ? [{ jp: item.example, cn: item.exampleCn }] : []),
    ...(item.examples || []),
    ...extraExamples
  ];
  return renderZelda40ExampleList(examples);
}

function renderZelda40Vocabulary(items, unitId, useExtraExamples = true) {
  return items.map((item, index) => {
    const conjugation = ZELDA40_VERB_FORMS[item.word];
    const conjugationId = `conjugation-zelda40-${unitId}-${index}`;
    const typeLabel = !conjugation && item.type
      ? `<div class="zelda-vocab-type">${zelda40Escape(item.type)}</div>`
      : '';
    return `
    <article class="zelda-vocab-card">
      <div class="zelda-vocab-word">${zelda40Escape(item.word)}<span class="zelda-reading">（${zelda40Escape(item.reading)}）</span></div>
      <div class="zelda-vocab-meaning">${zelda40Escape(item.meaning)}</div>
      ${typeLabel}
      ${renderZelda40Conjugation(conjugation, conjugationId)}
      ${renderZelda40Examples(item, useExtraExamples ? (ZELDA40_EXTRA_EXAMPLES[item.word] || []) : [])}
    </article>
  `;
  }).join('');
}

function renderZelda40Particles(items) {
  return items.map(item => `
    <article class="zelda-particle-card">
      <div class="zelda-grammar-pattern">🧩 ${zelda40Escape(item.pattern)}</div>
      <div class="zelda-particle-type">${zelda40Escape(item.category)}</div>
      <div class="zelda-particle-usage"><b>本篇功能：</b>${zelda40Escape(item.usage)}</div>
      ${renderZelda40ExampleList(item.examples || [])}
    </article>
  `).join('');
}

